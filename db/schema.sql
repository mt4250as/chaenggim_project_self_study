-- chaenggim DB schema (Oracle 21c XE, schema CHAENGGIM)
-- Tables, columns and constraints only; no data.

CREATE TABLE CODE_SEQUENCES (
    PREFIX               CHAR(1 BYTE) NOT NULL,
    SEQ_DATE             CHAR(6 BYTE) NOT NULL,
    LAST_SEQ             NUMBER(3) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CODE_SEQUENCES PRIMARY KEY (PREFIX, SEQ_DATE)
);

CREATE TABLE LIFE_EVENTS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PREFIX               CHAR(1 BYTE) NOT NULL,
    CODE                 VARCHAR2(30 BYTE) NOT NULL,
    NAME                 VARCHAR2(50 BYTE) NOT NULL,
    DESCRIPTION          VARCHAR2(500 BYTE),
    IS_ACTIVE            CHAR(1 BYTE) DEFAULT 'Y' NOT NULL,
    SORT_ORDER           NUMBER(3),
    CONSTRAINT PK_LIFE_EVENTS PRIMARY KEY (ID),
    CONSTRAINT UK_LIFE_EVENTS_PREFIX UNIQUE (PREFIX),
    CONSTRAINT UK_LIFE_EVENTS_CODE UNIQUE (CODE)
);

CREATE TABLE POLICIES (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    SOURCE               VARCHAR2(20 BYTE) NOT NULL,
    EXTERNAL_ID          VARCHAR2(100 BYTE) NOT NULL,
    TITLE                VARCHAR2(300 BYTE) NOT NULL,
    SUMMARY              CLOB,
    TARGET_AGE_MIN       NUMBER(3),
    TARGET_AGE_MAX       NUMBER(3),
    APPLY_URL            VARCHAR2(1000 BYTE),
    APPLY_START_DATE     DATE,
    APPLY_END_DATE       DATE,
    FETCHED_AT           TIMESTAMP(6) NOT NULL,
    IS_ACTIVE            CHAR(1 BYTE) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_POLICIES PRIMARY KEY (ID),
    CONSTRAINT UK_POLICY_SOURCE_EXT UNIQUE (SOURCE, EXTERNAL_ID)
);

CREATE TABLE USERS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    EMAIL                VARCHAR2(255 BYTE) NOT NULL,
    NAME                 VARCHAR2(50 BYTE) NOT NULL,
    BIRTH_DATE           DATE,
    CREATED_AT           TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP(6),
    DELETED_AT           TIMESTAMP(6),
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE USER_OAUTH_ACCOUNTS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID              NUMBER(19) NOT NULL,
    PROVIDER             VARCHAR2(20 BYTE) NOT NULL,
    PROVIDER_USER_ID     VARCHAR2(255 BYTE) NOT NULL,
    REFRESH_TOKEN        VARCHAR2(2000 BYTE),
    SCOPES               VARCHAR2(1000 BYTE),
    CREATED_AT           TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP(6),
    CONSTRAINT PK_USER_OAUTH_ACCOUNTS PRIMARY KEY (ID),
    CONSTRAINT UK_OAUTH_PROVIDER_UID UNIQUE (PROVIDER, PROVIDER_USER_ID),
    CONSTRAINT FK_USER_OAUTH_ACCOUNTS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

CREATE TABLE USER_SITUATIONS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID              NUMBER(19) NOT NULL,
    INPUT_TEXT           CLOB NOT NULL,
    LLM_MODEL            VARCHAR2(50 BYTE),
    LLM_RESPONSE         CLOB,
    STATUS               VARCHAR2(20 BYTE) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT           TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT           TIMESTAMP(6),
    CONSTRAINT PK_USER_SITUATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_USER_SITUATIONS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

CREATE TABLE CALENDAR_CONNECTIONS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID              NUMBER(19) NOT NULL,
    GOOGLE_CALENDAR_ID   VARCHAR2(255 BYTE) NOT NULL,
    SYNC_TOKEN           VARCHAR2(500 BYTE),
    LAST_SYNCED_AT       TIMESTAMP(6),
    STATUS               VARCHAR2(20 BYTE) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT           TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_CALENDAR_CONNECTIONS PRIMARY KEY (ID),
    CONSTRAINT UK_CALENDAR_CONNECTIONS_USER_ID UNIQUE (USER_ID),
    CONSTRAINT FK_CALENDAR_CONNECTIONS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

CREATE TABLE CHECKLIST_TEMPLATES (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODE                 VARCHAR2(20 BYTE) NOT NULL,
    EVENT_ID             NUMBER(19) NOT NULL,
    TITLE                VARCHAR2(100 BYTE) NOT NULL,
    DESCRIPTION          VARCHAR2(500 BYTE),
    IS_ACTIVE            CHAR(1 BYTE) DEFAULT 'Y' NOT NULL,
    SORT_ORDER           NUMBER(3),
    CONSTRAINT PK_CHECKLIST_TEMPLATES PRIMARY KEY (ID),
    CONSTRAINT UK_CHECKLIST_TEMPLATES_CODE UNIQUE (CODE),
    CONSTRAINT FK_CHECKLIST_TEMPLATES_EVENT_ID FOREIGN KEY (EVENT_ID) REFERENCES LIFE_EVENTS (ID)
);

CREATE TABLE EVENT_POLICIES (
    EVENT_ID             NUMBER(19) NOT NULL,
    POLICY_ID            NUMBER(19) NOT NULL,
    CONSTRAINT PK_EVENT_POLICIES PRIMARY KEY (EVENT_ID, POLICY_ID),
    CONSTRAINT FK_EVENT_POLICIES_EVENT_ID FOREIGN KEY (EVENT_ID) REFERENCES LIFE_EVENTS (ID),
    CONSTRAINT FK_EVENT_POLICIES_POLICY_ID FOREIGN KEY (POLICY_ID) REFERENCES POLICIES (ID)
);

CREATE TABLE PUSH_SUBSCRIPTIONS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID              NUMBER(19) NOT NULL,
    ENDPOINT             VARCHAR2(1000 BYTE) NOT NULL,
    P256DH_KEY           VARCHAR2(200 BYTE) NOT NULL,
    AUTH_KEY             VARCHAR2(100 BYTE) NOT NULL,
    USER_AGENT           VARCHAR2(500 BYTE),
    CREATED_AT           TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT           TIMESTAMP(6),
    CONSTRAINT PK_PUSH_SUBSCRIPTIONS PRIMARY KEY (ID),
    CONSTRAINT UK_PUSH_SUBSCRIPTIONS_ENDPOINT UNIQUE (ENDPOINT),
    CONSTRAINT FK_PUSH_SUBSCRIPTIONS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

CREATE TABLE TEMPLATE_ITEMS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODE                 VARCHAR2(20 BYTE) NOT NULL,
    TEMPLATE_ID          NUMBER(19) NOT NULL,
    CATEGORY             VARCHAR2(20 BYTE) NOT NULL,
    TITLE                VARCHAR2(200 BYTE) NOT NULL,
    AI_PROMPT_HINT       VARCHAR2(1000 BYTE),
    D_DAY_OFFSET         NUMBER(4),
    IS_REQUIRED          CHAR(1 BYTE) DEFAULT 'N' NOT NULL,
    SORT_ORDER           NUMBER(3),
    IS_ACTIVE            CHAR(1 BYTE) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_TEMPLATE_ITEMS PRIMARY KEY (ID),
    CONSTRAINT UK_TEMPLATE_ITEMS_CODE UNIQUE (CODE),
    CONSTRAINT FK_TEMPLATE_ITEMS_TEMPLATE_ID FOREIGN KEY (TEMPLATE_ID) REFERENCES CHECKLIST_TEMPLATES (ID)
);

CREATE TABLE USER_EVENTS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODE                 VARCHAR2(10 BYTE) NOT NULL,
    USER_ID              NUMBER(19) NOT NULL,
    EVENT_ID             NUMBER(19) NOT NULL,
    SITUATION_ID         NUMBER(19),
    TEMPLATE_ID          NUMBER(19),
    EVENT_DATE           DATE,
    SOURCE               VARCHAR2(10 BYTE) DEFAULT 'USER' NOT NULL,
    CONFIDENCE           NUMBER(3,2),
    STATUS               VARCHAR2(20 BYTE) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT           TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP(6),
    DELETED_AT           TIMESTAMP(6),
    CONSTRAINT PK_USER_EVENTS PRIMARY KEY (ID),
    CONSTRAINT UK_USER_EVENTS_CODE UNIQUE (CODE),
    CONSTRAINT FK_USER_EVENTS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_USER_EVENTS_EVENT_ID FOREIGN KEY (EVENT_ID) REFERENCES LIFE_EVENTS (ID),
    CONSTRAINT FK_USER_EVENTS_SITUATION_ID FOREIGN KEY (SITUATION_ID) REFERENCES USER_SITUATIONS (ID),
    CONSTRAINT FK_USER_EVENTS_TEMPLATE_ID FOREIGN KEY (TEMPLATE_ID) REFERENCES CHECKLIST_TEMPLATES (ID)
);
CREATE INDEX IX_UEVENT_USER_STATUS ON USER_EVENTS (USER_ID, STATUS);
CREATE INDEX IX_UEVENT_EVENT_DATE ON USER_EVENTS (EVENT_ID, CREATED_AT);

CREATE TABLE USER_CHECKLIST_ITEMS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_EVENT_ID        NUMBER(19) NOT NULL,
    TEMPLATE_ITEM_ID     NUMBER(19),
    POLICY_ID            NUMBER(19),
    TITLE                VARCHAR2(200 BYTE) NOT NULL,
    CONTENT              CLOB,
    SOURCE               VARCHAR2(10 BYTE) DEFAULT 'AI' NOT NULL,
    STATUS               VARCHAR2(20 BYTE) DEFAULT 'TODO' NOT NULL,
    DUE_DATE             DATE,
    COMPLETED_AT         TIMESTAMP(6),
    SORT_ORDER           NUMBER(3),
    GOOGLE_EVENT_ID      VARCHAR2(255 BYTE),
    CALENDAR_SYNCED_AT   TIMESTAMP(6),
    CREATED_AT           TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP(6),
    DELETED_AT           TIMESTAMP(6),
    CONSTRAINT PK_USER_CHECKLIST_ITEMS PRIMARY KEY (ID),
    CONSTRAINT FK_USER_CHECKLIST_ITEMS_USER_EVENT_ID FOREIGN KEY (USER_EVENT_ID) REFERENCES USER_EVENTS (ID),
    CONSTRAINT FK_USER_CHECKLIST_ITEMS_TEMPLATE_ITEM_ID FOREIGN KEY (TEMPLATE_ITEM_ID) REFERENCES TEMPLATE_ITEMS (ID),
    CONSTRAINT FK_USER_CHECKLIST_ITEMS_POLICY_ID FOREIGN KEY (POLICY_ID) REFERENCES POLICIES (ID)
);
CREATE INDEX IX_ITEM_EVENT_ORDER ON USER_CHECKLIST_ITEMS (USER_EVENT_ID, SORT_ORDER);
CREATE INDEX IX_ITEM_DUE_STATUS ON USER_CHECKLIST_ITEMS (DUE_DATE, STATUS);
CREATE INDEX IX_ITEM_GCAL ON USER_CHECKLIST_ITEMS (GOOGLE_EVENT_ID);

CREATE TABLE NOTIFICATIONS (
    ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID              NUMBER(19) NOT NULL,
    CHECKLIST_ITEM_ID    NUMBER(19),
    TYPE                 VARCHAR2(20 BYTE) NOT NULL,
    TITLE                VARCHAR2(200 BYTE) NOT NULL,
    BODY                 VARCHAR2(1000 BYTE),
    SCHEDULED_AT         TIMESTAMP(6) NOT NULL,
    SENT_AT              TIMESTAMP(6),
    STATUS               VARCHAR2(20 BYTE) DEFAULT 'PENDING' NOT NULL,
    READ_AT              TIMESTAMP(6),
    CREATED_AT           TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_NOTIFICATIONS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_NOTIFICATIONS_CHECKLIST_ITEM_ID FOREIGN KEY (CHECKLIST_ITEM_ID) REFERENCES USER_CHECKLIST_ITEMS (ID)
);
CREATE INDEX IX_NOTI_STATUS_TIME ON NOTIFICATIONS (STATUS, SCHEDULED_AT);

